"""
Switch Agent Bridge Interface Contract.
Defines boundary methods invoked by future Switch room connectors.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional
from backend.app.integrations.switch.contracts.schemas import (
    SwitchAgentCommand,
    SwitchRoomNotification,
)


class BaseSwitchAgentBridge(ABC):
    """Abstract interface defining the integration boundary between Switch and TenderForge."""

    @abstractmethod
    async def dispatch_room_command(self, command: SwitchAgentCommand) -> Dict[str, Any]:
        """Dispatch a command generated inside a Switch room to TenderForge services."""
        pass

    @abstractmethod
    async def broadcast_room_event(self, notification: SwitchRoomNotification) -> bool:
        """Broadcast an event generated by TenderForge to the Switch Room."""
        pass

